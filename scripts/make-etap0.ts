/** Excel в русской локали ждёт точку с запятой и BOM, иначе кириллица и колонки ломаются */
const csv = (name: string, rows: (string | number)[][]) => {
  const body = rows.map((r) => r.map((c) => (typeof c === "string" && /[;"\n]/.test(c) ? `"${c.replace(/"/g, '""')}"` : c)).join(";")).join("\r\n");
  writeFileSync(`${OUT}/${name}`, "﻿" + body + "\r\n", "utf8");
  console.log(`${name}: ${rows.length - 1} строк`);
};

